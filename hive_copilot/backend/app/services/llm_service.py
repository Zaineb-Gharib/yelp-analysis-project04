import os
import logging
import time
import re

import requests
from dotenv import load_dotenv

load_dotenv()

DEEPSEEK_API_KEY = os.getenv("DEEPSEEK_API_KEY", "")
logger = logging.getLogger(__name__)


def _make_query_plan(key: str, sql: str, summary: str):
    return type(
        "QueryPlan",
        (),
        {
            "key": key,
            "sql": sql,
            "summary": summary,
        },
    )()


def _strip_sql_fences(sql: str) -> str:
    return sql.replace("```sql", "").replace("```", "").strip()


def _request_llm_sql(full_prompt: str, fallback_sql: str, fallback_summary: str):
    started = time.perf_counter()

    if not DEEPSEEK_API_KEY:
        logger.info("llm.fallback missing_api_key duration_sec=%.2f", time.perf_counter() - started)
        return _make_query_plan("fallback", fallback_sql, fallback_summary)

    headers = {
        "Authorization": f"Bearer {DEEPSEEK_API_KEY}",
        "Content-Type": "application/json",
    }

    data = {
        "model": "deepseek-chat",
        "messages": [{"role": "user", "content": full_prompt}],
        "temperature": 0,
        "max_tokens": 300,
    }

    try:
        response = requests.post(
            "https://api.deepseek.com/v1/chat/completions",
            headers=headers,
            json=data,
            timeout=10,
        )
        if response.status_code == 200:
            sql = _strip_sql_fences(response.json()["choices"][0]["message"]["content"])
            logger.info(
                "llm.success status=%d duration_sec=%.2f",
                response.status_code,
                time.perf_counter() - started,
            )
            return _make_query_plan("query", sql, "Generated by DeepSeek")

        logger.warning(
            "llm.http_error status=%d duration_sec=%.2f",
            response.status_code,
            time.perf_counter() - started,
        )
        return _make_query_plan("fallback", fallback_sql, f"API error: {response.status_code}")
    except Exception as e:
        logger.exception(
            "llm.exception duration_sec=%.2f error=%s",
            time.perf_counter() - started,
            e,
        )
        return _make_query_plan("fallback", fallback_sql, f"Error: {str(e)[:50]}")

